/**
 * Returns a full Unsplash URL for a named photo.
 * @param {string} key  key of IDS
 * @param {number} w    requested width (next/image resizes again, this is the source size)
 */
export function img(key, w = 1600) {
  const id = IDS[key];
  if (!id) throw new Error(`Unknown image key: ${key}`);
  return `https://images.unsplash.com/photo-${id}?auto=format&fit=crop&w=${w}&q=75`;
}

